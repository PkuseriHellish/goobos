static const size_t font_glyph_count = sizeof(font_glyphs) / sizeof(font_glyphs[0]);

const font_glyph_t *font_get_glyph(uint32_t codepoint)
{
    size_t left = 0;
    size_t right = font_glyph_count;

    while (left < right) {
        size_t mid = left + (right - left) / 2;

        uint32_t value = font_glyphs[mid].codepoint;

        if (value == codepoint)
            return &font_glyphs[mid];

        if (value < codepoint)
            left = mid + 1;
        else
            right = mid;
    }

    return NULL;
}

void font_char(uint32_t codepoint, int x, int y, uint8_t color)
{
    const font_glyph_t *glyph = font_get_glyph(codepoint);

    if (!glyph)
        return;

    size_t bytes_per_row = (glyph->width + 7) / 8;

    for (size_t yy = 0; yy < glyph->height; yy++) {
        for (size_t xx = 0; xx < glyph->width; xx++) {

            size_t byte_index = yy * bytes_per_row + xx / 8;

            uint8_t bit = 7 - (xx % 8);

            int px = x + glyph->x_offset + (int)xx;
            int py = y + glyph->y_offset + (int)yy;

            if (glyph->bitmap[byte_index] & (1 << bit))
            {
                drawpx(px, py, color);
            }
        }
    }
}

void font_str(const char *str, int x, int y, uint8_t color)
{
    while (*str) {
        uint32_t codepoint = (uint8_t)*str;

        const font_glyph_t *glyph = font_get_glyph(codepoint);

        font_char(codepoint, x, y, color);

        if (glyph)
            x += glyph->advance;
        else
            x += 8;

        str++;
    }
}